  function pick() {
    const q = new URLSearchParams(location.search).get('lang');
    const cands = [q].concat(navigator.languages || [navigator.language || 'en']);
    for (const c of cands) {
      if (!c) continue;
      const l = String(c).toLowerCase().slice(0, 2);
      if (S[l]) return l;
    }
    return 'en';
  }

  const lang = pick();
  document.documentElement.lang = lang;
  window.MTLang = lang;
  // t('players', {n: 4}) — {x} placeholders; values are escaped by the caller's renderer.
  window.t = function (key, vars) {
    let s = (S[lang] && S[lang][key]) || S.en[key] || key;
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  };
