#!/usr/bin/env python3
"""Turn duplicates-batch3.json into the third migration.

Run:  set -a && . ./.env && set +a && python3 scripts/question-repair-ka/build-migration-3.py

Batches 1 and 2 are applied. Both of them rewrote question text — batch 1 to
shorten stems that overflowed the card, batch 2 to fix grammar and standardise
names. The duplicate clustering ran *before* either rewrite existed, so it
clustered text that is no longer in the bank, and it could not see the pairs
those rewrites created:

    "რომელი პლანეტაა ცნობილი თავისი სისტემით?"   (unclear, rewritten)
 -> "რომელი პლანეტაა ცნობილი თავისი რგოლებით?"   (already another question)

This pass re-clusters the live text. It groups every non-media question by its
correct answer, compares stems inside each group by word overlap and character
4-grams, and keeps only clusters containing at least one row whose text has
changed — clusters of untouched rows were already judged in batch 1.

The decisions are in duplicates-batch3.json, one object per cluster, each
naming the survivor and the rows it replaces. This script only emits them; it
verifies first that every id is live and that no id is named twice.
"""

import json
import os
import pathlib
import sys
import urllib.request

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / "supabase" / "migrations" / "20260817120000_question_repair_ka_batch3.sql"
DECISIONS = HERE / "duplicates-batch3.json"

SUPABASE_URL = os.environ.get("VITE_SUPABASE_URL")
SUPABASE_KEY = os.environ.get("VITE_SUPABASE_PUBLISHABLE_KEY")
if not SUPABASE_URL or not SUPABASE_KEY:
    sys.exit(
        "Missing VITE_SUPABASE_URL / VITE_SUPABASE_PUBLISHABLE_KEY.\n"
        "  set -a && . ./.env && set +a && python3 scripts/question-repair-ka/build-migration-3.py"
    )

COLUMNS = "id,question_text,correct_answer,quality_status"


def fetch_questions():
    rows, page = [], 1000
    for offset in range(0, 20000, page):
        url = (
            f"{SUPABASE_URL}/rest/v1/questions?select={COLUMNS}"
            f"&language=eq.ka&order=id&offset={offset}&limit={page}"
        )
        req = urllib.request.Request(
            url, headers={"apikey": SUPABASE_KEY, "Authorization": f"Bearer {SUPABASE_KEY}"}
        )
        with urllib.request.urlopen(req) as resp:
            batch = json.load(resp)
        rows.extend(batch)
        if len(batch) < page:
            break
    return rows


questions = fetch_questions()
by_short = {q["id"][:8]: q for q in questions}

clusters = json.loads(DECISIONS.read_text())

# ── check the decisions before emitting them ──────────────────────────────
problems = []
seen = {}
for c in clusters:
    for short in [c["keep"]] + c["retire"]:
        if short not in by_short:
            problems.append(f"{short} is not a live Georgian question")
        if short in seen:
            problems.append(f"{short} appears in two clusters: {seen[short]} and {c['note'][:40]}")
        seen[short] = c["note"][:40]
    if not c["retire"]:
        problems.append(f"cluster {c['keep']} retires nothing")
if problems:
    print("Decisions that cannot be applied:")
    for p in problems:
        print("  " + p)
    sys.exit(1)

retired = sum(len(c["retire"]) for c in clusters)
print(f"{len(clusters)} clusters · keep {len(clusters)} · retire {retired}")


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


lines = [
    "-- Georgian question bank repair, batch 3 — the duplicates the rewrites created.",
    "--",
    "-- Generated by scripts/question-repair-ka/build-migration-3.py from",
    "-- duplicates-batch3.json beside it. Regenerate rather than editing this by hand.",
    "--",
    "-- Batches 1 and 2 both rewrote question text: batch 1 shortened stems that",
    "-- overflowed the card, batch 2 fixed grammar and standardised names. The",
    "-- duplicate clustering ran before either rewrite existed, so it clustered text",
    "-- that is no longer in the bank. Re-clustering the live text turns up "
    f"{len(clusters)} groups",
    "-- of questions that now ask the same thing and take the same answer — one term",
    "-- written four ways became one term, and two stems became one sentence.",
    "--",
    "-- Each group keeps one row and retires the rest: is_active = false and",
    "-- in_production = false. Nothing is deleted, and every retired row names its",
    "-- survivor in the comment above it.",
    "",
    "BEGIN;",
    "",
]

for c in sorted(clusters, key=lambda c: by_short[c["keep"]]["question_text"]):
    keeper = by_short[c["keep"]]
    lines.append(f"-- {c['note']}")
    lines.append(f"--   keep {c['keep']}: {keeper['question_text']} -> {keeper['correct_answer']}")
    for short in c["retire"]:
        row = by_short[short]
        lines.append(f"--   drop {short}: {row['question_text']} -> {row['correct_answer']}")
        lines.append(
            "UPDATE public.questions SET is_active = false, in_production = false, "
            f"quality_status = 'retired_ka_repair', updated_at = now() WHERE id = {q(row['id'])};"
        )
    lines.append("")

lines += [
    "COMMIT;",
    "",
    "-- After this migration:",
    f"--   {retired} duplicate questions retired, across {len(clusters)} groups",
    "",
]

OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({len(lines)} lines)")
